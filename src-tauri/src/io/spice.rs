use std::collections::{HashMap, HashSet};
use crate::model::schematic::SchematicSheet;
use crate::model::library::Component;
use crate::engine::netlist::{extract_netlist_with_components, ComponentMap};

/// What kind of SPICE primitive a schematic symbol maps onto.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum DeviceKind {
    Resistor,
    Capacitor,
    Inductor,
    Diode,
    Led,
    Npn,
    Pnp,
    VoltageSource,
    Ground,
    Generic,
}

impl DeviceKind {
    fn classify(name: &str) -> Self {
        let lower = name.to_ascii_lowercase();
        if lower.contains("resistor") || lower == "r" {
            Self::Resistor
        } else if lower.contains("capacitor") || lower == "c" {
            Self::Capacitor
        } else if lower.contains("inductor") || lower == "l" {
            Self::Inductor
        } else if lower.contains("led") {
            Self::Led
        } else if lower.contains("diode") {
            Self::Diode
        } else if lower.contains("pnp") {
            Self::Pnp
        } else if lower.contains("npn") || lower.contains("transistor") || lower.contains("bjt") {
            Self::Npn
        } else if lower.contains("vcc")
            || lower.contains("vdd")
            || lower.contains("voltage source")
            || lower.contains("battery")
        {
            Self::VoltageSource
        } else if lower.contains("gnd") || lower.contains("ground") {
            Self::Ground
        } else {
            Self::Generic
        }
    }

    fn refdes_prefix(self) -> &'static str {
        match self {
            Self::Resistor => "R",
            Self::Capacitor => "C",
            Self::Inductor => "L",
            Self::Diode | Self::Led => "D",
            Self::Npn | Self::Pnp => "Q",
            Self::VoltageSource => "V",
            Self::Ground => "#PWR",
            Self::Generic => "X",
        }
    }
}

/// Generate a SPICE netlist from a schematic sheet.
pub fn generate_spice(
    sheet: &SchematicSheet,
    params: &HashMap<String, String>,
    components: &ComponentMap,
    analysis_override: Option<&str>,
) -> Result<String, String> {
    let mut next_id = 0usize;
    let netlist = extract_netlist_with_components(sheet, &mut next_id, components);

    // Node name for every net. Ground nets collapse onto SPICE node 0.
    let mut nodes: HashMap<String, String> = HashMap::new();
    let mut used: HashSet<String> = HashSet::new();
    used.insert("0".to_string());
    for net in &netlist.nets {
        let node = if is_ground_net(&net.name) {
            "0".to_string()
        } else {
            unique_node(&sanitize_node(&net.name), &mut used)
        };
        nodes.insert(net.name.clone(), node);
    }

    // (refdes, pin_number) -> node
    let mut pin_nodes: HashMap<(String, String), String> = HashMap::new();
    for net in &netlist.nets {
        let node = nodes.get(&net.name).cloned().unwrap_or_else(|| "0".to_string());
        for conn in &net.connections {
            pin_nodes.insert((conn.refdes.clone(), conn.pin_number.clone()), node.clone());
        }
    }

    let title = sheet
        .properties
        .get("title")
        .cloned()
        .unwrap_or_else(|| "TraceCraft Simulation".to_string());

    let mut out = String::new();
    out.push_str(&format!("TraceCraft - {title}\n"));
    out.push_str("* SPICE netlist generated by TraceCraft\n");

    let mut model_lines: Vec<String> = Vec::new();
    let mut emitted_models: HashSet<String> = HashSet::new();
    let mut warnings: Vec<String> = Vec::new();
    let mut voltage_nets: HashSet<String> = HashSet::new();
    let mut devices = 0usize;

    let mut symbols: Vec<(usize, &crate::model::schematic::SymbolInstance)> =
        sheet.symbols.iter().collect();
    symbols.sort_by_key(|(id, _)| *id);

    for (sym_id, sym) in symbols {
        let component = components.get(&sym.component_id);
        let kind = DeviceKind::classify(device_name(component, sym));
        let base_refdes = symbol_refdes(sym, sym_id);
        let base_refdes = clean_refdes(&base_refdes);
        let refdes = if base_refdes.starts_with(kind.refdes_prefix()) {
            base_refdes
        } else {
            format!("{}{}", kind.refdes_prefix(), base_refdes)
        };

        let node = |pin_number: &str| -> Option<String> {
            pin_nodes
                .get(&(sym.refdes.clone(), pin_number.to_string()))
                .cloned()
                .or_else(|| {
                    pin_nodes
                        .get(&(refdes.clone(), pin_number.to_string()))
                        .cloned()
                })
        };

        // Also try resolving by pin name for parts whose pins are named A/K/C/B/E.
        let pin_node_by_name = |name: &str| -> Option<String> {
            let pins = component?.symbol.pins.as_slice();
            let pin = pins.iter().find(|p| {
                p.name.eq_ignore_ascii_case(name) || p.number.eq_ignore_ascii_case(name)
            })?;
            pin_nodes
                .get(&(sym.refdes.clone(), pin.number.clone()))
                .cloned()
        };

        match kind {
            DeviceKind::Ground => {
                // Only a net-name carrier; nothing to emit.
                continue;
            }
            DeviceKind::Resistor | DeviceKind::Capacitor | DeviceKind::Inductor => {
                let (Some(a), Some(b)) = (node("1"), node("2")) else {
                    warnings.push(format!("{}: missing pin connectivity, skipped", refdes));
                    continue;
                };
                let value = resolve_value(kind, component, sym);
                let Some(value) = value else {
                    warnings.push(format!("{}: no electrical value, skipped", refdes));
                    continue;
                };
                let letter = match kind {
                    DeviceKind::Resistor => "R",
                    DeviceKind::Capacitor => "C",
                    _ => "L",
                };
                out.push_str(&format!("{}{} {} {} {}\n", letter, strip_prefix(&refdes, letter), a, b, value));
                devices += 1;
            }
            DeviceKind::Diode | DeviceKind::Led => {
                let anode = pin_node_by_name("A").or_else(|| node("1"));
                let cathode = pin_node_by_name("K").or_else(|| node("2"));
                let (Some(a), Some(k)) = (anode, cathode) else {
                    warnings.push(format!("{}: missing diode pins, skipped", refdes));
                    continue;
                };
                let model_name = if kind == DeviceKind::Led {
                    "DLED".to_string()
                } else {
                    sanitize_model_name(
                        component
                            .and_then(|c| c.parameters.get("spice_model"))
                            .map(|s| s.as_str())
                            .unwrap_or("DMOD"),
                    )
                };
                if emitted_models.insert(model_name.clone()) {
                    if kind == DeviceKind::Led {
                        model_lines.push(format!(
                            ".model {} D(Is=1e-20 N=1.8 Rs=10)",
                            model_name
                        ));
                    } else {
                        model_lines.push(format!(".model {} D(Is=1e-14 N=1.0)", model_name));
                    }
                }
                out.push_str(&format!(
                    "D{} {} {} {}\n",
                    strip_prefix(&refdes, "D"),
                    a,
                    k,
                    model_name
                ));
                devices += 1;
            }
            DeviceKind::Npn | DeviceKind::Pnp => {
                let collector = pin_node_by_name("C").or_else(|| node("2"));
                let base = pin_node_by_name("B").or_else(|| node("1"));
                let emitter = pin_node_by_name("E").or_else(|| node("3"));
                let (Some(c), Some(b), Some(e)) = (collector, base, emitter) else {
                    warnings.push(format!("{}: incomplete transistor pins, skipped", refdes));
                    continue;
                };
                let model_name = if kind == DeviceKind::Npn {
                    "QNPN"
                } else {
                    "QPNP"
                };
                if emitted_models.insert(model_name.to_string()) {
                    if kind == DeviceKind::Npn {
                        model_lines.push(
                            ".model QNPN NPN(Is=1e-14 Bf=100 Vaf=100)".to_string(),
                        );
                    } else {
                        model_lines.push(
                            ".model QPNP PNP(Is=1e-14 Bf=50 Vaf=100)".to_string(),
                        );
                    }
                }
                out.push_str(&format!(
                    "Q{} {} {} {} {}\n",
                    strip_prefix(&refdes, "Q"),
                    c,
                    b,
                    e,
                    model_name
                ));
                devices += 1;
            }
            DeviceKind::VoltageSource => {
                let Some(positive) = node("1") else {
                    warnings.push(format!("{}: unconnected power symbol, skipped", refdes));
                    continue;
                };
                if !voltage_nets.insert(positive.clone()) {
                    continue;
                }
                let voltage = resolve_value(DeviceKind::VoltageSource, component, sym)
                    .unwrap_or_else(|| "5".to_string());
                out.push_str(&format!(
                    "V{} {} 0 DC {}\n",
                    strip_prefix(&refdes, "V"),
                    positive,
                    voltage
                ));
                devices += 1;
            }
            DeviceKind::Generic => {
                warnings.push(format!(
                    "{} ({}): no SPICE model mapping, skipped",
                    refdes,
                    device_name(component, sym)
                ));
            }
        }
    }

    if devices == 0 {
        return Err(
            "No SPICE-compatible components found. Supported: R, C, L, D, LED, NPN/PNP, VCC, GND."
                .to_string(),
        );
    }

    if !model_lines.is_empty() {
        out.push_str("\n* Device models\n");
        for line in &model_lines {
            out.push_str(line);
            out.push('\n');
        }
    }

    if !warnings.is_empty() {
        out.push_str("\n* Warnings\n");
        for warning in &warnings {
            out.push_str(&format!("* {}\n", warning));
        }
    }

    let analysis = analysis_override
        .map(|s| s.to_string())
        .or_else(|| params.get("analysis").cloned())
        .unwrap_or_else(|| ".tran 1m 100m".to_string());
    let analysis = normalize_analysis(&analysis)?;

    out.push_str("\n* Analysis\n");
    out.push_str(".option filetype=ascii\n");
    out.push_str(&analysis);
    out.push('\n');
    out.push_str(".end\n");

    Ok(out)
}

pub fn export_spice(
    sheet: &SchematicSheet,
    path: &str,
    params: &HashMap<String, String>,
    components: &ComponentMap,
    analysis: Option<&str>,
) -> Result<(), String> {
    let netlist = generate_spice(sheet, params, components, analysis)?;
    std::fs::write(path, netlist)
        .map_err(|e| format!("Failed to write SPICE netlist to {}: {}", path, e))
}

// ── Helpers ────────────────────────────────────────────────────────────────

fn device_name<'a>(
    component: Option<&'a Component>,
    sym: &'a crate::model::schematic::SymbolInstance,
) -> &'a str {
    component
        .map(|c| c.name.as_str())
        .filter(|n| !n.is_empty())
        .unwrap_or(if sym.value.is_empty() {
            "component"
        } else {
            sym.value.as_str()
        })
}

fn symbol_refdes(sym: &crate::model::schematic::SymbolInstance, id: usize) -> String {
    if sym.refdes.trim().is_empty() {
        format!("X{}", id + 1)
    } else {
        sym.refdes.trim().to_string()
    }
}

fn clean_refdes(refdes: &str) -> String {
    let cleaned: String = refdes
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '_')
        .collect();
    if cleaned.is_empty() {
        "X1".to_string()
    } else if cleaned.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(false) {
        format!("X{}", cleaned)
    } else {
        cleaned
    }
}

fn strip_prefix(refdes: &str, prefix: &str) -> String {
    refdes
        .strip_prefix(prefix)
        .unwrap_or(refdes)
        .to_string()
        .replace(' ', "_")
}

fn resolve_value(
    kind: DeviceKind,
    component: Option<&Component>,
    sym: &crate::model::schematic::SymbolInstance,
) -> Option<String> {
    let explicit = sym.value.trim();
    let component_name = component.map(|c| c.name.as_str()).unwrap_or("");
    let explicit_is_value = !explicit.is_empty()
        && !explicit.eq_ignore_ascii_case(component_name)
        && explicit.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(false);

    if explicit_is_value {
        return Some(normalize_value(explicit));
    }

    let params = component.map(|c| &c.parameters);
    let keys: &[&str] = match kind {
        DeviceKind::Resistor => &["Resistance", "Value", "resistance", "value"],
        DeviceKind::Capacitor => &["Capacitance", "Value", "capacitance", "value"],
        DeviceKind::Inductor => &["Inductance", "Value", "inductance", "value"],
        DeviceKind::VoltageSource => &["Voltage", "voltage", "Value", "value"],
        _ => &["Value", "value"],
    };

    for key in keys {
        if let Some(value) = params.and_then(|p| p.get(*key)) {
            let value = normalize_value(value);
            if !value.is_empty() {
                return Some(value);
            }
        }
    }

    // Last resort for passives: a safe default keeps the netlist simulatable.
    match kind {
        DeviceKind::Resistor => Some("1k".to_string()),
        DeviceKind::Capacitor => Some("100n".to_string()),
        DeviceKind::Inductor => Some("1u".to_string()),
        DeviceKind::VoltageSource => Some("5".to_string()),
        _ => None,
    }
}

/// Strip engineering unit suffixes that SPICE would misread as scale factors
/// (e.g. `100nF` -> `100n`, `5V` -> `5`).
fn normalize_value(value: &str) -> String {
    let mut v = value.trim().replace(' ', "").replace('µ', "u");
    for unit in ["ohms", "ohm", "farads", "farad", "henries", "henry", "volts", "volt", "amps", "amp"] {
        if v.to_ascii_lowercase().ends_with(unit) {
            let keep = v.len() - unit.len();
            v.truncate(keep);
            break;
        }
    }
    let mut chars: Vec<char> = v.chars().collect();
    while let Some(last) = chars.last().copied() {
        let is_unit = matches!(last, 'F' | 'f' | 'V' | 'v' | 'H' | 'h' | 'A' | 'a' | 'Ω' | 'R' | 'r');
        let prev = if chars.len() >= 2 {
            chars[chars.len() - 2]
        } else {
            '\0'
        };
        let prev_ok = prev.is_ascii_digit() || matches!(prev, 'n' | 'u' | 'p' | 'k' | 'K' | 'M' | 'm' | 'G' | 'T');
        if is_unit && prev_ok {
            chars.pop();
        } else {
            break;
        }
    }
    chars.into_iter().collect()
}

fn is_ground_net(name: &str) -> bool {
    let lower = name.trim().to_ascii_lowercase();
    lower == "0" || lower == "gnd" || lower == "ground" || lower == "gnd_ref"
}

fn sanitize_node(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' })
        .collect();
    while out.contains("__") {
        out = out.replace("__", "_");
    }
    let out = out.trim_matches('_').to_string();
    if out.is_empty() {
        return "N".to_string();
    }
    if out.chars().next().map(|c| c.is_ascii_digit()).unwrap_or(false) {
        return format!("N{}", out);
    }
    out
}

fn unique_node(base: &str, used: &mut HashSet<String>) -> String {
    if used.insert(base.to_string()) {
        return base.to_string();
    }
    let mut i = 2;
    loop {
        let candidate = format!("{}_{}", base, i);
        if used.insert(candidate.clone()) {
            return candidate;
        }
        i += 1;
    }
}

fn sanitize_model_name(name: &str) -> String {
    let cleaned: String = name
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() || c == '_' { c } else { '_' })
        .collect();
    if cleaned.is_empty() {
        "DMOD".to_string()
    } else {
        cleaned
    }
}

fn normalize_analysis(analysis: &str) -> Result<String, String> {
    let trimmed = analysis.trim();
    if trimmed.is_empty() {
        return Err("Analysis directive is empty".to_string());
    }
    let with_dot = if trimmed.starts_with('.') {
        trimmed.to_string()
    } else {
        format!(".{}", trimmed)
    };
    let lower = with_dot.to_ascii_lowercase();
    let known = [".tran", ".ac", ".dc", ".op", ".noise", ".four", ".disto", ".pz", ".sens"];
    if !known.iter().any(|k| lower.starts_with(k)) {
        return Err(format!(
            "Unsupported analysis directive '{}'. Use .tran, .ac, .dc, or .op.",
            trimmed
        ));
    }
    if with_dot.contains('\n') || with_dot.contains('\r') {
        return Err("Analysis directive must be a single line".to_string());
    }
    Ok(with_dot)
}
