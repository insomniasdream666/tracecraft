use std::collections::HashMap;
use crate::model::schematic::SchematicSheet;
use crate::engine::netlist::extract_netlist;

/// Map component names to SPICE prefixes
fn spice_prefix(name: &str) -> &str {
    let lower = name.to_lowercase();
    if lower.contains("resistor") || lower.starts_with("r") { "R" }
    else if lower.contains("capacitor") || lower.starts_with("c") { "C" }
    else if lower.contains("inductor") || lower.starts_with("l") { "L" }
    else if lower.contains("diode") || lower.starts_with("d") { "D" }
    else if lower.contains("transistor") || lower.contains("npn") || lower.contains("pnp") || lower.starts_with("q") { "Q" }
    else if lower.contains("vcc") || lower.contains("vdd") || lower.contains("source") || lower.starts_with("v") { "V" }
    else if lower.contains("gnd") || lower.contains("ground") || lower.starts_with("g") { "G" }
    else if lower.contains("led") { "D" }
    else if lower.contains("mosfet") || lower.contains("mos") { "M" }
    else if lower.contains("opamp") || lower.contains("op-amp") || lower.contains("u") { "X" }
    else { "X" }
}

/// Infer a SPICE model string from a component name and its parameters
fn spice_model(name: &str, value: &str, params: &HashMap<String, String>) -> Option<String> {
    let lower = name.to_lowercase();
    if lower.contains("resistor") {
        return Some(format!("{{}} {value}"));
    }
    if lower.contains("capacitor") {
        return Some(format!("{{}} {value}"));
    }
    if lower.contains("inductor") {
        return Some(format!("{{}} {value}"));
    }
    if lower.contains("diode") || lower.contains("led") {
        let model = params.get("spice_model").cloned().unwrap_or_else(|| "1N4148".to_string());
        return Some(format!("{{}} {model}"));
    }
    if lower.contains("npn") || lower.contains("transistor") {
        let model = params.get("spice_model").cloned().unwrap_or_else(|| "2N2222".to_string());
        return Some(format!("{{}} {model}"));
    }
    if lower.contains("vcc") || lower.contains("vdd") || lower.contains("voltage") {
        let voltage = params.get("voltage").cloned().unwrap_or_else(|| value.to_string());
        if voltage.is_empty() {
            return Some("{{}} DC 5".to_string());
        }
        return Some(format!("{{}} DC {voltage}"));
    }
    if lower.contains("gnd") || lower.contains("ground") {
        return Some("{{}} 0".to_string());
    }
    // Generic: try to use value as a model parameter
    if !value.is_empty() {
        return Some(format!("{{}} {value}"));
    }
    None
}

/// Generate a SPICE netlist from a schematic sheet
pub fn generate_spice(sheet: &SchematicSheet, params: &HashMap<String, String>) -> Result<String, String> {
    let mut output = String::new();
    let title = sheet.properties.get("title").cloned().unwrap_or_else(|| "TraceCraft Simulation".to_string());
    output.push_str(&format!("* SPICE Netlist generated by TraceCraft\n"));
    output.push_str(&format!(".title {title}\n\n"));

    // Extract the electrical netlist
    let mut next_id = 0usize;
    let netlist = extract_netlist(sheet, &mut next_id);

    // Build a pin-to-net mapping per refdes
    // For simplicity, we map each symbol's first pin to net 0 (GND)
    // and assume a 2-pin component model
    let mut refdes_pins: HashMap<String, Vec<(String, String)>> = HashMap::new();

    for net in &netlist.nets {
        for conn in &net.connections {
            refdes_pins.entry(conn.refdes.clone())
                .or_default()
                .push((conn.pin_number.clone(), format!("N${}", net.name)));
        }
    }

    // Write components
    for (_, sym) in sheet.symbols.iter() {
        let prefix = spice_prefix(&sym.value);
        let model = spice_model(&sym.value, &sym.value, params);
        let refdes = sym.refdes.trim_start_matches('R').to_string();

        let pins = refdes_pins.get(&sym.refdes).cloned().unwrap_or_default();
        let net_a = pins.first().map(|(_, n)| n.as_str()).unwrap_or("0");
        let net_b = pins.get(1).map(|(_, n)| n.as_str()).unwrap_or("0");

        let instance_line = match model {
            Some(ref m) if m.contains("{}") => {
                format!("{}{} {} {} {}", prefix, refdes, net_a, net_b, m.replace("{}", &sym.value))
            }
            Some(m) => {
                format!("{}{} {} {} {}", prefix, refdes, net_a, net_b, m)
            }
            None => {
                format!("{}{} {} {} {}", prefix, refdes, net_a, net_b, sym.value)
            }
        };
        output.push_str(&instance_line);
        output.push('\n');
    }

    // Write net aliases for readability
    output.push_str("\n* Net aliases\n");
    for net in &netlist.nets {
        output.push_str(&format!("{} N${}\n", net.name, net.name));
    }

    // Write simulation directives from parameters
    output.push_str("\n* Simulation commands\n");
    let analysis = params.get("analysis").map(|s| s.as_str()).unwrap_or(".tran 1m 100m");
    output.push_str(&format!("{analysis}\n"));
    output.push_str(".control\nrun\nprint all\n.endc\n.end\n");

    Ok(output)
}

/// Export SPICE netlist to a file
pub fn export_spice(sheet: &SchematicSheet, path: &str, params: &HashMap<String, String>) -> Result<(), String> {
    let netlist = generate_spice(sheet, params)?;
    std::fs::write(path, &netlist).map_err(|e| format!("Failed to write SPICE file: {e}"))
}
